-- Tabel member per dashboard (Step 2 "Informasi Member & Hak Akses").
-- Member dipilih dari MASTER_USER (opsi B), jadi USERNAME FK ke MASTER_USER.
-- Isolasi tenant lewat kolom TENANT (fashion/kemenkeu).
-- =====================================================================

CREATE TABLE DASHBOARD_MEMBER (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  DASHBOARD_ID  VARCHAR2(100) NOT NULL,          -- id dashboard (databaseId di app)
  TENANT        VARCHAR2(20)  NOT NULL,          -- fashion | kemenkeu
  USERNAME      VARCHAR2(100) NOT NULL,          -- member, dari MASTER_USER
  ROLE_ACCESS   VARCHAR2(30)  DEFAULT 'viewer' NOT NULL, -- viewer|editor|pengelola
  UNIT          VARCHAR2(200),
  IS_ACTIVE     NUMBER(1) DEFAULT 1 NOT NULL,
  IS_DELETED    NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_BY    VARCHAR2(100),
  CREATED_TIME  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY    VARCHAR2(100),
  UPDATED_TIME  TIMESTAMP,
  CONSTRAINT FK_DASHMEMBER_USER FOREIGN KEY (USERNAME) REFERENCES MASTER_USER (USERNAME),
  CONSTRAINT UQ_DASHMEMBER UNIQUE (DASHBOARD_ID, TENANT, USERNAME),
  CONSTRAINT CK_DASHMEMBER_ROLE   CHECK (ROLE_ACCESS IN ('viewer','editor','pengelola')),
  CONSTRAINT CK_DASHMEMBER_TENANT CHECK (TENANT IN ('fashion','kemenkeu')),
  CONSTRAINT CK_DASHMEMBER_ACTIVE  CHECK (IS_ACTIVE  IN (0,1)),
  CONSTRAINT CK_DASHMEMBER_DELETED CHECK (IS_DELETED IN (0,1))
);
CREATE INDEX IX_DASHMEMBER_DASH ON DASHBOARD_MEMBER (DASHBOARD_ID, TENANT);
CREATE INDEX IX_DASHMEMBER_USER ON DASHBOARD_MEMBER (USERNAME);
