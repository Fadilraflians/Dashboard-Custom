CREATE TABLE MASTER_USER (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME           VARCHAR2(150)  NOT NULL,
  USERNAME       VARCHAR2(100)  NOT NULL,
  EMAIL          VARCHAR2(200),
  PASSWORD_HASH  VARCHAR2(255)  NOT NULL,
  MINISTRY_CODE  VARCHAR2(50)   NOT NULL,
  IS_ADMIN       NUMBER(1) DEFAULT 0 NOT NULL,
  TOTP_SECRET     VARCHAR2(255),
  IS_TOTP_ENABLED NUMBER(1) DEFAULT 0 NOT NULL,
  IS_ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
  IS_DELETED     NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_BY     VARCHAR2(100),
  CREATED_TIME   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY     VARCHAR2(100),
  UPDATED_TIME   TIMESTAMP,
  CONSTRAINT UQ_MASTER_USER_USERNAME UNIQUE (USERNAME),
  CONSTRAINT CK_MASTER_USER_IS_ADMIN     CHECK (IS_ADMIN   IN (0, 1)),
  CONSTRAINT CK_MASTER_USER_IS_TOTP      CHECK (IS_TOTP_ENABLED IN (0, 1)),
  CONSTRAINT CK_MASTER_USER_IS_ACTIVE  CHECK (IS_ACTIVE  IN (0, 1)),
  CONSTRAINT CK_MASTER_USER_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);
CREATE INDEX IX_MASTER_USER_MINISTRY ON MASTER_USER (MINISTRY_CODE);

CREATE TABLE MASTER_ROLE (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE           VARCHAR2(100)  NOT NULL,
  NAME           VARCHAR2(150)  NOT NULL,
  MINISTRY_CODE  VARCHAR2(50)   NOT NULL,
  IS_ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
  IS_DELETED     NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_BY     VARCHAR2(100),
  CREATED_TIME   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY     VARCHAR2(100),
  UPDATED_TIME   TIMESTAMP,
  CONSTRAINT UQ_MASTER_ROLE_CODE UNIQUE (CODE),
  CONSTRAINT CK_MASTER_ROLE_IS_ACTIVE  CHECK (IS_ACTIVE  IN (0, 1)),
  CONSTRAINT CK_MASTER_ROLE_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);
CREATE INDEX IX_MASTER_ROLE_MINISTRY ON MASTER_ROLE (MINISTRY_CODE);

CREATE TABLE MASTER_APPLICATION (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE           VARCHAR2(100)  NOT NULL,
  NAME           VARCHAR2(200)  NOT NULL,
  CATEGORY       VARCHAR2(100),
  TAGS           VARCHAR2(500),
  DESCRIPTION    VARCHAR2(1000),
  MINISTRY_CODE  VARCHAR2(50)   NOT NULL,
  ORDER_BY       NUMBER(6) DEFAULT 0 NOT NULL,
  IS_ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
  IS_DELETED     NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_BY     VARCHAR2(100),
  CREATED_TIME   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY     VARCHAR2(100),
  UPDATED_TIME   TIMESTAMP,
  CONSTRAINT UQ_MASTER_APP_CODE UNIQUE (CODE),
  CONSTRAINT CK_MASTER_APP_IS_ACTIVE  CHECK (IS_ACTIVE  IN (0, 1)),
  CONSTRAINT CK_MASTER_APP_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);
CREATE INDEX IX_MASTER_APP_MINISTRY ON MASTER_APPLICATION (MINISTRY_CODE);

CREATE TABLE APPLICATION_WIDGETS (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  APPS_CODE      VARCHAR2(100)  NOT NULL,
  TYPE           VARCHAR2(40)   NOT NULL,
  TITLE          VARCHAR2(500)  NOT NULL,
  COMPONENT_NAME VARCHAR2(255),
  DATA           CLOB,
  LAYOUT         CLOB,
  IS_ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
  IS_DELETED     NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_BY     VARCHAR2(100),
  CREATED_TIME   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY     VARCHAR2(100),
  UPDATED_TIME   TIMESTAMP,
  CONSTRAINT FK_APPWIDGET_APP
    FOREIGN KEY (APPS_CODE) REFERENCES MASTER_APPLICATION (CODE) ON DELETE CASCADE,
  CONSTRAINT CK_APPWIDGET_IS_ACTIVE  CHECK (IS_ACTIVE  IN (0, 1)),
  CONSTRAINT CK_APPWIDGET_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);
CREATE INDEX IX_APPWIDGET_APPS_CODE ON APPLICATION_WIDGETS (APPS_CODE);

CREATE TABLE MAPPING_USER_ROLE (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ROLE_CODE      VARCHAR2(100)  NOT NULL,
  USERNAME       VARCHAR2(100)  NOT NULL,
  IS_ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
  IS_DELETED     NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_BY     VARCHAR2(100),
  CREATED_TIME   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY     VARCHAR2(100),
  UPDATED_TIME   TIMESTAMP,
  CONSTRAINT FK_MAPUSERROLE_ROLE FOREIGN KEY (ROLE_CODE) REFERENCES MASTER_ROLE (CODE),
  CONSTRAINT FK_MAPUSERROLE_USER FOREIGN KEY (USERNAME)  REFERENCES MASTER_USER (USERNAME),
  CONSTRAINT UQ_MAPUSERROLE UNIQUE (ROLE_CODE, USERNAME),
  CONSTRAINT CK_MAPUSERROLE_IS_ACTIVE  CHECK (IS_ACTIVE  IN (0, 1)),
  CONSTRAINT CK_MAPUSERROLE_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);
CREATE INDEX IX_MAPUSERROLE_ROLE ON MAPPING_USER_ROLE (ROLE_CODE);
CREATE INDEX IX_MAPUSERROLE_USER ON MAPPING_USER_ROLE (USERNAME);

CREATE TABLE MAPPING_APPLICATION_ROLE (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ROLE_CODE      VARCHAR2(100)  NOT NULL,
  APPS_CODE      VARCHAR2(100)  NOT NULL,
  IS_ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
  IS_DELETED     NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_BY     VARCHAR2(100),
  CREATED_TIME   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY     VARCHAR2(100),
  UPDATED_TIME   TIMESTAMP,
  CONSTRAINT FK_MAPAPPROLE_ROLE FOREIGN KEY (ROLE_CODE) REFERENCES MASTER_ROLE (CODE),
  CONSTRAINT FK_MAPAPPROLE_APP  FOREIGN KEY (APPS_CODE) REFERENCES MASTER_APPLICATION (CODE),
  CONSTRAINT UQ_MAPAPPROLE UNIQUE (ROLE_CODE, APPS_CODE),
  CONSTRAINT CK_MAPAPPROLE_IS_ACTIVE  CHECK (IS_ACTIVE  IN (0, 1)),
  CONSTRAINT CK_MAPAPPROLE_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);
CREATE INDEX IX_MAPAPPROLE_ROLE ON MAPPING_APPLICATION_ROLE (ROLE_CODE);
CREATE INDEX IX_MAPAPPROLE_APP  ON MAPPING_APPLICATION_ROLE (APPS_CODE);


