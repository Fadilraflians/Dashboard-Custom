CREATE TABLE FASHION_SALES (
  ID NUMBER(10) NOT NULL,
  ORDER_ID VARCHAR2(30) NOT NULL,
  ORDER_DATE TIMESTAMP NOT NULL,
  CUSTOMER_NAME VARCHAR2(150),
  CITY VARCHAR2(150),
  PRODUCT_NAME VARCHAR2(150),
  UNIT_PRICE NUMBER(14,2),
  QUANTITY NUMBER(10),
  DISCOUNT_PERCENT NUMBER(7,2),
  SUBTOTAL NUMBER(16,2),
  DISCOUNT_AMOUNT NUMBER(16,2),
  TOTAL_SALES NUMBER(16,2),
  SHIPPING_FEE NUMBER(14,2),
  GRAND_TOTAL NUMBER(16,2),
  PAYMENT_METHOD VARCHAR2(100),
  ORDER_STATUS VARCHAR2(40),
  PLATFORM VARCHAR2(150),
  CUSTOMER_RATING NUMBER(4,2),
  PRODUCT_SIZE VARCHAR2(20),
  MATERIAL VARCHAR2(100),
  GENDER VARCHAR2(30),
  CONSTRAINT PK_FASHION_SALES PRIMARY KEY (ID)
);

CREATE INDEX IX_FASHION_SALES_ORDER ON FASHION_SALES (ORDER_ID);
CREATE INDEX IX_FASHION_SALES_DATE ON FASHION_SALES (ORDER_DATE);
CREATE INDEX IX_FASHION_SALES_PRODUCT ON FASHION_SALES (PRODUCT_NAME);
CREATE INDEX IX_FASHION_SALES_CITY ON FASHION_SALES (CITY);
